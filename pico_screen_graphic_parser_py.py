from PIL import Image

#replace handOn with your image's filename, ofc
filename = 'handOn'
img = Image.open(filename+'.png')
img = img.convert('RGBA')
myWidth = img.width
pixels = img.load()
stringout = ''
xsize = 1
largestX = -1
width, height = img.size

for y in range(height):
    largestX = -1
    first = False
    for x in range(width): #read each pixel group
        if(x > largestX and pixels[x, y] == (255, 255, 255, 255)):
            r, g, b, a = pixels[x, y]
            xsize = 1
            seenBlack = False
            while(x+xsize < width and seenBlack == False):
                if(pixels[x+xsize, y] == (255, 255, 255, 255)):
                    xsize += 1
                    largestX = x+xsize
                else:
                    seenBlack = True
            if(not first):
              first = True
              stringout += f"{x},{xsize}"
            else:
              stringout += f",{x},{xsize}"
    if(y != height-1):
      stringout += '\n'

with open(filename+".txt", "w", encoding="utf-8") as file:
    file.write(stringout)

